WITH staging AS (


SELECT
    ICAO24,
    CALLSIGN,
    COUNTRY,
    LONGITUDE,
    LATITUDE,
    BARO_ALTITUDE,
    VELOCITY,
    TRUE_TRACK,
    POSITION_TIMESTAMP
FROM {{ ref('stg_opensky_stages') }}


)

SELECT
ICAO24 AS AIRCRAFT_ID,
TRIM(CALLSIGN) AS CALLSIGN,
COUNTRY,
LATITUDE,
LONGITUDE,
BARO_ALTITUDE AS ALTITUDE,
VELOCITY AS SPEED,
TRUE_TRACK AS HEADING,
POSITION_TIMESTAMP,


CASE
    WHEN BARO_ALTITUDE IS NULL OR BARO_ALTITUDE <= 0 THEN NULL
    ELSE BARO_ALTITUDE * 3.28084
END AS ALTITUDE_FT


FROM staging
